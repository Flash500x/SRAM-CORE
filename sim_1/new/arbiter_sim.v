`timescale 1ns / 1ps

module arbiter_sim;

    //==================================================
    // SIGNALS
    //==================================================

    reg clk;
    reg rst;
    reg a;
    reg b;

    wire rg;
    wire wg;


    //==================================================
    // DUT
    //==================================================

    arbiter art(
        .clk(clk),
        .rst(rst),
        .a(a),
        .b(b),
        .rg(rg),
        .wg(wg)
    );


    //==================================================
    // CLOCK
    //==================================================

    always #5 clk = ~clk;


    //==================================================
    // TEST
    //==================================================

    initial begin

        //================================================
        // INITIAL VALUES
        //================================================

        clk = 0;
        rst = 0;
        a   = 0;
        b   = 0;


        //================================================
        // RESET
        //================================================

        #10;
        rst = 1;


        //================================================
        // TEST 1
        // READ REQUEST ONLY
        // a = 1, b = 0
        // EXPECT: rg = 1
        //================================================

        #10;
        a = 1;
        b = 0;

        #10;
        a = 0;


        //================================================
        // TEST 2
        // WRITE REQUEST ONLY
        // a = 0, b = 1
        // EXPECT: wg = 1
        //================================================

        #10;
        b = 1;

        #10;
        b = 0;


        //================================================
        // TEST 3
        // BOTH REQUESTS
        // Current priority: WRITE
        // EXPECT: wg = 1
        //================================================

        #10;
        a = 1;
        b = 1;

        #10;
        a = 0;
        b = 0;


        //================================================
        // TEST 4
        // BOTH REQUESTS AGAIN
        // Priority should alternate to READ
        // EXPECT: rg = 1
        //================================================

        #10;
        a = 1;
        b = 1;

        #10;
        a = 0;
        b = 0;


        //================================================
        // TEST 5
        // BOTH REQUESTS AGAIN
        // Priority should alternate to WRITE
        // EXPECT: wg = 1
        //================================================

        #10;
        a = 1;
        b = 1;

        #10;
        a = 0;
        b = 0;


        //================================================
        // TEST 6
        // NO REQUEST
        // EXPECT: rg = 0, wg = 0
        //================================================

        #10;
        a = 0;
        b = 0;


        //================================================
        // FINISH
        //================================================

        #20;

        $finish;

    end

endmodule