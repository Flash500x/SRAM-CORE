`timescale 1ns / 1ps

module top_module_tb();

parameter DATA_WIDTH    = 8;
parameter ADDRESS_WIDTH = 8;

// ============================================================
// CONTROLLER 1 : 10 ns period (5 ns half period)
// ============================================================

reg req, rw, clk, rst, bmode, abort;
reg [3:0] burst_len;
reg [1:0] burst_type;
reg [ADDRESS_WIDTH-1:0] addr;

reg [DATA_WIDTH-1:0] data_in;

wire done,op_complete,data_valid;
wire busy;
wire [DATA_WIDTH-1:0] data_out;


// ============================================================
// CONTROLLER 2 : 14 ns period (7 ns half period)
// ============================================================

reg clk2;
reg rst2;
reg req2;
reg [ADDRESS_WIDTH-1:0] addr2;

wire [DATA_WIDTH-1:0] rdata2;
wire done2;
wire busy2;


// ============================================================
// DUT
// ============================================================

top_module #(
    .ADDRESS_WIDTH(ADDRESS_WIDTH),
    .DATA_WIDTH(DATA_WIDTH)
) uut (

    // Controller 1
    .req(req),
    .rw(rw),
    .clk(clk),
    .rst(rst),
    .bmode(bmode),
    .abort(abort),
    .burst_len(burst_len),
    .burst_type(burst_type),
    .addr(addr),

    .done(done),
    .busy(busy),

    .data_in(data_in),
    .data_out(data_out),
    .data_valid(data_valid),

    // Controller 2
    .clk2(clk2),
    .rst2(rst2),
    .req2(req2),
    .addr2(addr2),
    .op_complete(op_complete),
    
    .rdata2(rdata2),
    .done2(done2),
    .busy2(busy2)
);


// ============================================================
// CLOCKS
// ============================================================

// Controller 1 : 5 ns half period -> 10 ns period
always #5 clk = ~clk;

// Controller 2 : 7 ns half period -> 14 ns period
always #7 clk2 = ~clk2;


// ============================================================
// TEST
// ============================================================

initial begin

    $dumpfile("wave.vcd");
    $dumpvars(0, top_module_tb);

    // --------------------------------------------------------
    // Initial values
    // --------------------------------------------------------

    clk  = 0;
    clk2 = 0;

    rst  = 0;
    rst2 = 0;

    req   = 0;
    req2  = 0;

    rw    = 0;
    bmode = 0;
    abort = 0;

    addr  = 0;
    addr2 = 0;

    data_in = 0;

    burst_len  = 4'd0;
    burst_type = 2'b00;


    // ========================================================
    // RESET
    // ========================================================

    // Controller 1 reset: 1 clock cycle
    #10;
    rst = 1;

    // Controller 2 reset: 1 clock cycle
    #4;
    rst2 = 1;


    // ========================================================
    // CONTROLLER 1
    // ========================================================

    // --------------------------------------------------------
    // Burst write
    // 01 = 02
    // 02 = 03
    // 03 = 07
    // --------------------------------------------------------

    #20;

    addr       = 8'h01;
    req        = 1'b1;
    bmode      = 1'b1;
    rw         = 1'b1;
    burst_len  = 4'd3;
    burst_type = 2'b01;

    data_in    = 8'h02;

    #30;

    req     = 1'b0;
    data_in = 8'h03;

    #30;

    data_in = 8'h07;

    #30;

    bmode = 1'b0;
    rw    = 1'b0;


    // --------------------------------------------------------
    // Burst read
    // 01, 02, 03
    // --------------------------------------------------------

    #30;

    req        = 1'b1;
    bmode      = 1'b1;
    rw         = 1'b0;
    addr       = 8'h01;
    burst_len  = 4'd3;
    burst_type = 2'b01;

    #90;

    req   = 1'b0;
    bmode = 1'b0;


    // --------------------------------------------------------
    // Normal write
    // 04 = 05
    // --------------------------------------------------------

    #30;

    req       = 1'b1;
    rw        = 1'b1;
    bmode     = 1'b0;
    addr      = 8'h04;
    data_in   = 8'h05;
    burst_len = 4'd1;

    #30;

    req = 1'b0;
    rw  = 1'b0;


    // --------------------------------------------------------
    // Normal read
    // 04
    // --------------------------------------------------------

    #30;

    req  = 1'b1;
    rw   = 1'b0;
    bmode = 1'b0;
    addr = 8'h04;

    #30;

    req = 1'b0;


    // --------------------------------------------------------
    // Normal writes
    // 10 = AA
    // 11 = 55
    // 12 = F0
    // --------------------------------------------------------

    #30;

    req     = 1'b1;
    rw      = 1'b1;
    bmode   = 1'b0;
    addr    = 8'h10;
    data_in = 8'hAA;

    #30;

    req = 1'b0;

    #30;

    req     = 1'b1;
    addr    = 8'h11;
    data_in = 8'h55;

    #30;

    req = 1'b0;

    #30;

    req     = 1'b1;
    addr    = 8'h12;
    data_in = 8'hF0;

    #30;

    req = 1'b0;


    // --------------------------------------------------------
    // Normal reads
    // 10
    // 11
    // 12
    // --------------------------------------------------------

    #30;

    req  = 1'b1;
    rw   = 1'b0;
    addr = 8'h10;

    #30;

    req = 1'b0;

    #30;

    req  = 1'b1;
    addr = 8'h11;

    #30;

    req = 1'b0;

    #30;

    req  = 1'b1;
    addr = 8'h12;

    #30;

    req = 1'b0;


    // --------------------------------------------------------
    // Single-word burst write
    // 20 = CC
    // --------------------------------------------------------

    #30;

    req        = 1'b1;
    rw         = 1'b1;
    bmode      = 1'b1;
    burst_len  = 4'd1;
    addr       = 8'h20;
    data_in    = 8'hCC;
    burst_type = 2'b01;

    #30;

    req   = 1'b0;
    bmode = 1'b0;
    rw    = 1'b0;


    // --------------------------------------------------------
    // Single-word burst read
    // --------------------------------------------------------

    #30;

    req        = 1'b1;
    rw         = 1'b0;
    bmode      = 1'b1;
    burst_len  = 4'd1;
    addr       = 8'h20;
    burst_type = 2'b01;

    #30;

    req   = 1'b0;
    bmode = 1'b0;


    // --------------------------------------------------------
    // Burst write before abort
    // 30 = 11
    // 31 = 22
    // then abort
    // --------------------------------------------------------

    #30;

    req        = 1'b1;
    rw         = 1'b1;
    bmode      = 1'b1;
    burst_len  = 4'd4;
    addr       = 8'h30;
    data_in    = 8'h11;
    burst_type = 2'b01;

    #30;

    req     = 1'b0;
    data_in = 8'h22;

    // Abort after approximately 3 controller-1 cycles
    #20;

    abort = 1'b1;

    #10;

    abort     = 1'b0;
    bmode     = 1'b0;
    rw        = 1'b0;


    // --------------------------------------------------------
    // Transaction after abort
    // 40 = 77
    // --------------------------------------------------------

    #30;

    req       = 1'b1;
    rw        = 1'b1;
    bmode     = 1'b0;
    burst_len = 4'd1;
    addr      = 8'h40;
    data_in   = 8'h77;

    #30;

    req = 1'b0;
    rw  = 1'b0;


    // --------------------------------------------------------
    // Read after abort
    // --------------------------------------------------------

    #30;

    req   = 1'b1;
    rw    = 1'b0;
    addr  = 8'h40;

    #30;

    req = 1'b0;


    // ========================================================
    // CONTROLLER 2 : rd_fsm
    // ========================================================

    // Give controller 2 some time before its tests
    #28;

    // --------------------------------------------------------
    // Read address 00
    // --------------------------------------------------------

    req2  = 1'b1;
    addr2 = 8'h00;

    #14;

    req2 = 1'b0;

    #28;


    // --------------------------------------------------------
    // Read address 01
    // --------------------------------------------------------

    req2  = 1'b1;
    addr2 = 8'h01;

    #14;

    req2 = 1'b0;

    #28;


    // --------------------------------------------------------
    // Read address 10
    // --------------------------------------------------------

    req2  = 1'b1;
    addr2 = 8'h10;

    #14;

    req2 = 1'b0;

    #28;


    // --------------------------------------------------------
    // Read address 20
    // --------------------------------------------------------

    req2  = 1'b1;
    addr2 = 8'h20;

    #14;

    req2 = 1'b0;

    #28;


    // --------------------------------------------------------
    // Finish
    // --------------------------------------------------------

    #100;

    $finish;

end

endmodule